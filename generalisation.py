"""Generalisation study: 100 random scenarios (scenario_gen, seed 7) through the SAME pipeline function as the CLI
(run.run_pipeline, seed 0).  Writes logs/generalisation.json and logs/generalisation.md.

    python generalisation.py

Scenarios with C_rand - C* < 1.0 are listed but excluded from the lift/enrichment summary (ratio unstable; the
organisers exclude such scenarios too).
"""
import json
import os
import tempfile
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import numpy as np

import run
from scenario_gen import random_scenario

ROOT = Path(__file__).resolve().parent
MIN_DENOM = 1.0


def one(sc):
    with tempfile.TemporaryDirectory() as d:
        p = Path(d) / "scenario.json"
        p.write_text(json.dumps(sc))
        m = run.run_pipeline(str(p), 0, str(Path(d) / "out"))
    q = m["baselines"]["qubo_minimiser"]
    return {"name": sc["name"], "C_star": m["C_star"], "C_rand": m["C_rand"],
            "denominator": m["C_rand"] - m["C_star"], "qubo_regret_pct": q["regret_percent_of_C_star"],
            "lift": m["lift"], "enrichment": m["elite_enrichment"], "runtime_seconds": m["runtime_seconds"],
            "evals": m["qaoa"]["training_evaluations"]}


def stats(x):
    x = np.asarray(x, float)
    return {"mean": float(x.mean()), "min": float(x.min()), "p10": float(np.percentile(x, 10)), "max": float(x.max())}


def main():
    rng = np.random.default_rng(7)
    scs = [random_scenario(rng, f"gen{i:03d}") for i in range(100)]
    with ProcessPoolExecutor(max_workers=os.cpu_count()) as ex:
        rows = list(ex.map(one, scs))
    ok = [r for r in rows if r["denominator"] >= MIN_DENOM]
    reg = np.array([r["qubo_regret_pct"] for r in rows])
    summary = {"scenarios": len(rows), "excluded_small_denominator": [r["name"] for r in rows if r["denominator"] < MIN_DENOM],
               "lift": stats([r["lift"] for r in ok]), "enrichment": stats([r["enrichment"] for r in ok]),
               "qubo_regret_pct": {**stats(reg), "share_le_5pct": float((reg <= 5).mean()), "share_le_25pct": float((reg <= 25).mean())},
               "runtime_seconds": stats([r["runtime_seconds"] for r in rows]),
               "max_training_evaluations": max(r["evals"] for r in rows)}
    (ROOT / "logs").mkdir(exist_ok=True)
    (ROOT / "logs" / "generalisation.json").write_text(json.dumps({"generator_seed": 7, "pipeline_seed": 0,
                                                                   "summary": summary, "scenarios": rows}, indent=1))
    s = summary
    L = ["# Generalisation study (generated by generalisation.py)", "",
         f"{s['scenarios']} random scenarios from the section-7 ranges (scenario_gen seed 7), run through `run.run_pipeline` "
         f"with seed 0. Excluded from lift/enrichment (C_rand - C* < {MIN_DENOM}): {s['excluded_small_denominator'] or 'none'}.", "",
         "| metric | mean | min | 10th percentile | max |", "|---|---|---|---|---|"]
    for k, lab in [("lift", "lift"), ("enrichment", "elite enrichment"), ("qubo_regret_pct", "QUBO regret % of C*"), ("runtime_seconds", "runtime (s)")]:
        v = s[k]
        L.append(f"| {lab} | {v['mean']:.3f} | {v['min']:.3f} | {v['p10']:.3f} | {v['max']:.3f} |")
    L += ["", f"Share of scenarios with QUBO regret <= 5 %: **{s['qubo_regret_pct']['share_le_5pct']:.2f}**; "
              f"<= 25 %: {s['qubo_regret_pct']['share_le_25pct']:.2f}. Max training evaluations: {s['max_training_evaluations']}.", "",
          "## Per scenario", "", "| scenario | C* | C_rand | QUBO regret % | lift | enrichment | runtime s |", "|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['name']} | {r['C_star']} | {r['C_rand']:.2f} | {r['qubo_regret_pct']:.2f} | {r['lift']:.3f} | "
                 f"{r['enrichment']:.2f} | {r['runtime_seconds']:.1f} |")
    (ROOT / "logs" / "generalisation.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[:12]))


if __name__ == "__main__":
    main()
